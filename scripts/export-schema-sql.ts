// Writes db/neon-setup.sql: every statement db:setup would run, as one file
// you can paste into the Neon SQL Editor (no terminal needed). Safe to re-run.
// Usage: npm run db:schema-sql
import { writeFileSync } from "node:fs";
import { ensureSchema } from "../db/ensureSchema.js";

const statements: string[] = [];
const recorder = {
  query: async (sql: string) => {
    statements.push(sql.trim().replace(/^\s{2,}/gm, "  ").replace(/;?$/, ";"));
    return { rows: [], rowCount: 0 };
  },
};

await ensureSchema(recorder as any);

const out = [
  "-- Restaurant app: create all tables on Neon.",
  "-- Paste this whole file into Neon -> SQL Editor and click Run. Safe to run again.",
  "-- Generated by `npm run db:schema-sql` from db/ensureSchema.ts. Do not edit by hand.",
  "",
  ...statements,
  "",
].join("\n\n");

writeFileSync("db/neon-setup.sql", out);
console.log(`Wrote db/neon-setup.sql (${statements.length} statements).`);
