// Writes db/neon-setup.sql: every migration in migrations/, in order, as one
// file you can paste into the Neon SQL Editor (no terminal needed).
// It also records each migration in app_schema_migrations with the same
// checksum `npm run db:migrate` uses, so the two ways never disagree.
// Every statement is additive (IF NOT EXISTS), so it is safe to run again.
// Usage: npm run db:schema-sql
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { migrationFiles } from "../server/migrations.js";

const parts: string[] = [
  "-- Restaurant app: create or update all tables on Neon.",
  "-- Paste this whole file into Neon -> SQL Editor and click Run. Safe to run again.",
  "-- Generated by `npm run db:schema-sql` from migrations/*.sql. Do not edit by hand.",
  "",
  `CREATE TABLE IF NOT EXISTS app_schema_migrations (
  name text PRIMARY KEY, checksum text NOT NULL, applied_at timestamptz NOT NULL DEFAULT NOW()
);`,
];

for (const name of migrationFiles) {
  const sql = await readFile(new URL(`../migrations/${name}`, import.meta.url), "utf8");
  const checksum = createHash("sha256").update(sql).digest("hex");
  parts.push(
    `-- ===== ${name} =====`,
    sql.trim(),
    `INSERT INTO app_schema_migrations (name, checksum) VALUES ('${name}', '${checksum}') ON CONFLICT (name) DO NOTHING;`
  );
}

await writeFile(new URL("../db/neon-setup.sql", import.meta.url), parts.join("\n\n") + "\n");
console.log(`Wrote db/neon-setup.sql from ${migrationFiles.length} migrations.`);
