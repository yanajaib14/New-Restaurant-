ALTER TABLE task_todos ADD COLUMN IF NOT EXISTS "linkUrl" TEXT;

ALTER TABLE task_todos ADD COLUMN IF NOT EXISTS note TEXT;

ALTER TABLE task_todos ADD COLUMN IF NOT EXISTS subtasks JSONB DEFAULT '[]'::jsonb;

