-- Additive application schema for Neon. No seed records or public-access policies.
-- Existing tables/records are retained. Never run destructive schema.sql.

CREATE TABLE IF NOT EXISTS tasks (
      id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      category TEXT NOT NULL,
      task TEXT NOT NULL,
      due TEXT NOT NULL DEFAULT '',
      status TEXT NOT NULL DEFAULT 'Not Started',
      priority TEXT NOT NULL DEFAULT 'Medium',
      checklist JSONB DEFAULT '[]'::jsonb,
      "assignedTo" TEXT,
      "isCritical" BOOLEAN DEFAULT false,
      "linkedNoteId" BIGINT,
      created_at TIMESTAMPTZ DEFAULT NOW()
    );

ALTER TABLE tasks ADD COLUMN IF NOT EXISTS "linkedNoteId" BIGINT;

CREATE TABLE IF NOT EXISTS task_todos (
      id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
      title TEXT NOT NULL,
      category TEXT NOT NULL,
      status TEXT NOT NULL DEFAULT 'Not Started',
      "assignedTo" TEXT,
      "linkedTaskId" BIGINT,
      "linkUrl" TEXT,
      note TEXT,
      subtasks JSONB DEFAULT '[]'::jsonb,
      created_at TIMESTAMPTZ DEFAULT NOW()
